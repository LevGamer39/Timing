def greeting(role: str | None, name: str) -> str:
    """Приветствие по роли; без роли здороваемся как с учеником."""
    template = GREETINGS.get(role or "", GREETINGS["student"])
    return template.format(name=esc(name))


def _online_hint() -> str:
    """Абзац со ссылкой на сайт; без APP_DOMAIN показывать нечего."""
    domain = settings.app_domain.rstrip("/")
    if not domain:
        return ""
    url = domain if "://" in domain else f"https://{domain}"
    return f"\n\n{ONLINE_HINT} {url}"


def help_text(role: str | None) -> str:
    """Справка по роли: учителю и админу не нужны команды ученика."""
    if role == "teacher":
        base = TEACHER_HELP_TEXT
    elif role == "admin":
        base = ADMIN_HELP_TEXT
    elif role == "parent":
        base = PARENT_HELP_TEXT
    else:
        base = HELP_TEXT
    return base + _online_hint()

