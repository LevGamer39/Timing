// Остальные журналы — псевдослучайные, но одинаковые при каждом запуске.
function rng(seed) {
  return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}
function generated(names, dates, types, seed) {
  const r = rng(seed);
  const base = names.map(() => 45 + Math.floor(r() * 50));
  return {
    dates, types,
    hw: dates.map((_, i) => '§' + (6 + i) + ', № ' + (10 + i * 4) + '–' + (13 + i * 4)),
    rows: names.map((_, i) => dates.map((d, j) => {
      if (j === dates.length - 1) return '';
      const x = r();
      if (x < 0.05) return 'Н';
      if (x < 0.5) return '';
      return Math.max(20, Math.min(100, Math.round(base[i] + (r() - 0.5) * 30)));
    })),
    comments: {}
  };
}

